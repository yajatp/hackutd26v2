"""Write fixtures.json: golden vectors for the TypeScript port.
- key_cases: the 20 answer-key pump failures (inputs = key onset facts) + expected plan
- random_cases: 60 random single + 15 random joint cases with this planner's output
Each case: system, fleet_free, failures[{event_id, facility_id, level_pct, horizon_min}]
and expected[{event_id, kind, trucks, trips_per_truck, shut_ins, cost}]."""
import json, os, random, sys, datetime as dt
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from planner import Failure, load_network, plan_joint, plan_sequential
import validate as V
REPO = sys.argv[1]; HIST = os.path.join(REPO, "history")
net = load_network(os.path.join(HIST, "full_week"))

def pj(p):
    return {"event_id": p.event_id, "kind": p.kind, "trucks": p.trucks,
            "trips_per_truck": p.trips_per_truck,
            "shut_ins": [{"well_id": w, "start_after_min": s} for w, s in p.shut_ins],
            "cost": round(p.cost, 2), "label": p.label()}

out = {"note": "Generated by make_fixtures.py from planner.py; network/ops = history/full_week",
       "rules": {"strict_shutdown": True, "shut_in_start_rounding": "ceil(exact)-1 whole minutes",
                 "tie_break": ["cost (cents)", "fewest trucks", "fewest trips"]},
       "key_cases": [], "random_cases": []}
# full_week sequential, each as its own case with the free-truck count it saw
key = json.load(open(os.path.join(HIST, "full_week", "answer_key.json")))
pf = [e for e in key if e["category"] == "pump_failure"]
t0 = min(e["onset_unix"] for e in key)
items = [((e["onset_unix"] - t0) / 60, Failure(e["id"], net.facilities[e["facility"]], float(e["level_pct"]), net.repair_min)) for e in pf]
plans = {p.event_id: p for p in plan_sequential(items, net)}
for e in pf:
    p = plans[e["id"]]
    out["key_cases"].append({"source": "full_week", "system": e["system"], "fleet_free": p.free_trucks,
        "failures": [{"event_id": e["id"], "facility_id": e["facility"], "level_pct": e["level_pct"], "horizon_min": net.repair_min}],
        "expected": [pj(p)], "key_reference_action": [e["reference_action"]]})
for snap in V.SNAPS:
    key = json.load(open(os.path.join(HIST, snap, "answer_key.json")))
    now = int(dt.datetime.strptime(snap.split("_")[1], "%Y-%m-%dT%H%M").replace(tzinfo=dt.timezone.utc).timestamp())
    by = {}
    for e in key:
        if e["category"] == "pump_failure" and e["status"] == "ongoing":
            H = e["onset_unix"] / 60 + net.repair_min - now / 60
            by.setdefault(e["system"], []).append((e, Failure(e["id"], net.facilities[e["facility"]], float(e["level_final_pct"]), H)))
    for sid, lst in by.items():
        ps, _ = plan_joint([f for _, f in lst], net, net.fleet[sid])
        out["key_cases"].append({"source": snap, "system": sid, "fleet_free": net.fleet[sid],
            "failures": [{"event_id": f.event_id, "facility_id": f.facility.id, "level_pct": f.level_pct, "horizon_min": f.horizon_min} for _, f in lst],
            "expected": [pj(p) for p in ps], "key_reference_action": [e["reference_action"] for e, _ in lst]})
random.seed(2026)
bysys = {}
for f in net.facilities.values():
    bysys.setdefault(f.system, []).append(f)
for i in range(75):
    sid = random.choice(sorted(bysys))
    k = 1 if i < 60 else random.randint(2, len(bysys[sid]))
    facs = random.sample(bysys[sid], k)
    F = random.randint(0, net.fleet[sid])
    fs = [Failure(f"R{i}_{j}", fa, round(random.uniform(25, 89), 1), float(random.choice([360, 330, 300, 240, 180, 120, 90]))) for j, fa in enumerate(facs)]
    ps, _ = plan_joint(fs, net, F)
    out["random_cases"].append({"source": "random", "system": sid, "fleet_free": F,
        "failures": [{"event_id": f.event_id, "facility_id": f.facility.id, "level_pct": f.level_pct, "horizon_min": f.horizon_min} for f in fs],
        "expected": [pj(p) for p in ps]})
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fixtures.json")
json.dump(out, open(path, "w"), indent=1)
kinds = {}
for c in out["random_cases"]:
    for x in c["expected"]:
        kinds[x["kind"]] = kinds.get(x["kind"], 0) + 1
print("wrote", path, len(out["key_cases"]), "key cases,", len(out["random_cases"]), "random cases; random kinds:", kinds)
